"""Anthropic Messages <-> OpenAI chat-completions translation. Pure functions and one small state machine; no I/O.

Mapping (research/02-bridge.md section 6):

* ``system`` -> a ``system`` message; ``thinking`` blocks -> assistant ``reasoning_content`` (and back);
* ``tool_use`` -> assistant ``tool_calls`` (arguments as a JSON string); ``tool_result`` -> ``tool`` messages that
  directly follow the call, before any text of the same user turn;
* ``tool_choice`` any/tool/auto/none -> required/function/auto/none;
* the reasoning text comes back as a ``thinking`` block whose ``signature`` is generated by the bridge
  (``sign``), because an OpenAI-style host has nothing Anthropic could verify. Replay is lenient: text is
  mapped back verbatim whatever the signature says.
"""

from __future__ import annotations

import hashlib
import hmac
import json
import os
import secrets
import uuid
from typing import Any

_KEY = os.environ.get("GLMKIT_BRIDGE_SIGNING_KEY", "").encode() or secrets.token_bytes(32)
SIG_PREFIX = "glmkit-v1."

STOP_REASONS = {
    "stop": "end_turn",
    "length": "max_tokens",
    "tool_calls": "tool_use",
    "function_call": "tool_use",
    "content_filter": "refusal",
    "sensitive": "refusal",
}
ERROR_TYPES = {
    400: "invalid_request_error",
    401: "authentication_error",
    402: "billing_error",
    403: "permission_error",
    404: "not_found_error",
    413: "request_too_large",
    429: "rate_limit_error",
    503: "overloaded_error",
    504: "timeout_error",
    529: "overloaded_error",
}


def sign(text: str) -> str:
    """Opaque signature for reasoning text produced by an upstream that has none."""
    return SIG_PREFIX + hmac.new(_KEY, text.encode(), hashlib.sha256).hexdigest()[:32]


def is_ours(signature: str, text: str) -> bool:
    return signature == sign(text)


def error_type(status: int) -> str:
    return ERROR_TYPES.get(status, "api_error" if status >= 500 else "invalid_request_error")


def error_body(status: int, message: str, request_id: str | None = None, etype: str | None = None) -> dict[str, Any]:
    out: dict[str, Any] = {"type": "error", "error": {"type": etype or error_type(status), "message": message}}
    if request_id:
        out["request_id"] = request_id
    return out


def new_message_id() -> str:
    return "msg_" + uuid.uuid4().hex[:24]


# ------------------------------------------------------------------------------------------ usage


def anthropic_usage(usage: dict[str, Any] | None) -> dict[str, Any]:
    """OpenAI usage -> Anthropic usage (``input_tokens`` excludes cache reads, as Anthropic reports it)."""
    u = usage or {}
    prompt = int(u.get("prompt_tokens") or 0)
    cached = int(((u.get("prompt_tokens_details") or {}).get("cached_tokens")) or 0)
    return {
        "input_tokens": max(0, prompt - cached),
        "output_tokens": int(u.get("completion_tokens") or 0),
        "cache_creation_input_tokens": 0,
        "cache_read_input_tokens": cached,
    }


def openai_usage(usage: dict[str, Any] | None) -> dict[str, Any] | None:
    """Anthropic usage -> the OpenAI shape that middleware (spend accounting) reads."""
    if not isinstance(usage, dict):
        return None
    cached = int(usage.get("cache_read_input_tokens") or 0)
    prompt = int(usage.get("input_tokens") or 0) + cached + int(usage.get("cache_creation_input_tokens") or 0)
    out = int(usage.get("output_tokens") or 0)
    return {
        "prompt_tokens": prompt,
        "completion_tokens": out,
        "total_tokens": prompt + out,
        "prompt_tokens_details": {"cached_tokens": cached},
    }


def total_input(usage: dict[str, Any] | None) -> int:
    u = usage or {}
    return int(
        (u.get("input_tokens") or 0)
        + (u.get("cache_read_input_tokens") or 0)
        + (u.get("cache_creation_input_tokens") or 0)
    )


# ------------------------------------------------------------------------------------------ request


def block_text(content: Any) -> str:
    if content is None:
        return ""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return "".join(
            b.get("text", "") if isinstance(b, dict) and b.get("type") == "text" else (b if isinstance(b, str) else "")
            for b in content
        )
    return str(content)


def _image(block: dict[str, Any]) -> dict[str, Any] | None:
    src = block.get("source") or {}
    if src.get("type") == "base64":
        return {
            "type": "image_url",
            "image_url": {"url": f"data:{src.get('media_type', 'image/png')};base64,{src.get('data', '')}"},
        }
    if src.get("type") == "url":
        return {"type": "image_url", "image_url": {"url": src.get("url", "")}}
    return None


def _user_messages(content: Any) -> list[dict[str, Any]]:
    if isinstance(content, str):
        return [{"role": "user", "content": content}]
    tools: list[dict[str, Any]] = []
    parts: list[dict[str, Any]] = []
    for b in content or []:
        if not isinstance(b, dict):
            continue
        t = b.get("type")
        if t == "tool_result":
            text = block_text(b.get("content"))
            if b.get("is_error"):
                text = "[error] " + text
            tools.append({"role": "tool", "tool_call_id": b.get("tool_use_id"), "content": text})
        elif t == "text":
            parts.append({"type": "text", "text": b.get("text", "")})
        elif t == "image":
            img = _image(b)
            if img:
                parts.append(img)
    out = list(tools)
    if parts:
        if all(p["type"] == "text" for p in parts):
            out.append({"role": "user", "content": "".join(p["text"] for p in parts)})
        else:
            out.append({"role": "user", "content": parts})
    return out


def _assistant_message(content: Any) -> dict[str, Any]:
    if isinstance(content, str):
        return {"role": "assistant", "content": content}
    text, reasoning, calls = [], [], []
    for b in content or []:
        if not isinstance(b, dict):
            continue
        t = b.get("type")
        if t == "text":
            text.append(b.get("text", ""))
        elif t == "thinking":
            reasoning.append(b.get("thinking", ""))
        elif t == "tool_use":
            calls.append(
                {
                    "id": b.get("id"),
                    "type": "function",
                    "function": {
                        "name": b.get("name"),
                        "arguments": json.dumps(b.get("input") or {}, ensure_ascii=False),
                    },
                }
            )
    msg: dict[str, Any] = {"role": "assistant", "content": "".join(text) or None}
    if reasoning:
        msg["reasoning_content"] = "".join(reasoning)
    if calls:
        msg["tool_calls"] = calls
    return msg


def _tool_choice(tc: Any) -> tuple[Any, bool | None]:
    if not isinstance(tc, dict):
        return None, None
    parallel = False if tc.get("disable_parallel_tool_use") else None
    kind = tc.get("type")
    if kind == "any":
        return "required", parallel
    if kind == "tool":
        return {"type": "function", "function": {"name": tc.get("name")}}, parallel
    if kind == "none":
        return "none", parallel
    return "auto", parallel


def to_openai_request(body: dict[str, Any]) -> dict[str, Any]:
    """Anthropic Messages request -> OpenAI chat-completions request. Never mutates ``body``."""
    out: dict[str, Any] = {"model": body.get("model"), "messages": []}
    system = block_text(body.get("system"))
    if system:
        out["messages"].append({"role": "system", "content": system})
    replay = False
    for m in body.get("messages") or []:
        if not isinstance(m, dict):
            continue
        if m.get("role") == "assistant":
            msg = _assistant_message(m.get("content"))
            replay = replay or "reasoning_content" in msg
            out["messages"].append(msg)
        else:
            out["messages"].extend(_user_messages(m.get("content")))
    if body.get("max_tokens") is not None:
        out["max_tokens"] = body["max_tokens"]
    for k in ("temperature", "top_p"):
        if body.get(k) is not None:
            out[k] = body[k]
    if body.get("stop_sequences"):
        out["stop"] = list(body["stop_sequences"])
    tools = [
        {
            "type": "function",
            "function": {
                "name": t["name"],
                "description": t.get("description") or "",
                "parameters": t.get("input_schema") or {"type": "object", "properties": {}},
            },
        }
        for t in body.get("tools") or []
        if isinstance(t, dict) and t.get("name") and t.get("type", "custom") == "custom"
    ]
    if tools:
        out["tools"] = tools
        choice, parallel = _tool_choice(body.get("tool_choice"))
        if choice is not None:
            out["tool_choice"] = choice
        if parallel is not None:
            out["parallel_tool_calls"] = parallel
    thinking = body.get("thinking")
    if isinstance(thinking, dict) and thinking.get("type"):
        kind = str(thinking["type"]).lower()
        th: dict[str, Any] = {"type": "enabled" if kind in ("enabled", "adaptive") else kind}
        if th["type"] == "enabled" and replay:
            th["clear_thinking"] = False  # keep earlier reasoning: the replayed history is what the model reads
        out["thinking"] = th
    effort = (body.get("output_config") or {}).get("effort") if isinstance(body.get("output_config"), dict) else None
    if effort:
        out["reasoning_effort"] = effort
    if body.get("stream"):
        out["stream"] = True
        out["stream_options"] = {"include_usage": True}
    return out


# ------------------------------------------------------------------------------------------ response


def _tool_input(arguments: Any) -> dict[str, Any]:
    if isinstance(arguments, dict):
        return arguments
    try:
        val = json.loads(arguments) if isinstance(arguments, str) and arguments.strip() else {}
    except ValueError:
        return {}
    return val if isinstance(val, dict) else {}


def from_openai_response(data: dict[str, Any], *, message_id: str | None = None) -> dict[str, Any]:
    """OpenAI chat-completions response (after the core's repairs) -> Anthropic message."""
    choice = (data.get("choices") or [{}])[0]
    msg = choice.get("message") or {}
    content: list[dict[str, Any]] = []
    reasoning = msg.get("reasoning_content") or msg.get("reasoning")
    if isinstance(reasoning, str) and reasoning:
        content.append({"type": "thinking", "thinking": reasoning, "signature": sign(reasoning)})
    if msg.get("content"):
        content.append({"type": "text", "text": msg["content"]})
    for tc in msg.get("tool_calls") or []:
        fn = tc.get("function") or {}
        content.append(
            {
                "type": "tool_use",
                "id": tc.get("id") or "toolu_" + uuid.uuid4().hex[:20],
                "name": fn.get("name", ""),
                "input": _tool_input(fn.get("arguments")),
            }
        )
    return {
        "id": message_id or new_message_id(),
        "type": "message",
        "role": "assistant",
        "model": data.get("model"),
        "content": content,
        "stop_reason": STOP_REASONS.get(choice.get("finish_reason") or "stop", "end_turn"),
        "stop_sequence": None,
        "usage": anthropic_usage(data.get("usage")),
    }


# ------------------------------------------------------------------------------------------ streaming


def sse_event(event: dict[str, Any]) -> bytes:
    data = json.dumps(event, ensure_ascii=False, separators=(",", ":"))
    return f"event: {event.get('type', 'message')}\ndata: {data}\n\n".encode()


def events_from_message(msg: dict[str, Any]) -> list[dict[str, Any]]:
    """Replay a finished Anthropic message as a stream (used where the bridge had to run the call itself)."""
    usage = msg.get("usage") or {}
    start = {k: v for k, v in msg.items() if k not in ("content", "stop_reason", "stop_sequence")}
    start.update(content=[], stop_reason=None, stop_sequence=None, usage={**usage, "output_tokens": 1})
    out: list[dict[str, Any]] = [{"type": "message_start", "message": start}, {"type": "ping"}]
    for i, b in enumerate(msg.get("content") or []):
        t = b.get("type")
        if t == "text":
            out += [
                {"type": "content_block_start", "index": i, "content_block": {"type": "text", "text": ""}},
                {"type": "content_block_delta", "index": i, "delta": {"type": "text_delta", "text": b.get("text", "")}},
            ]
        elif t == "thinking":
            out += [
                {
                    "type": "content_block_start",
                    "index": i,
                    "content_block": {"type": "thinking", "thinking": "", "signature": ""},
                },
                {
                    "type": "content_block_delta",
                    "index": i,
                    "delta": {"type": "thinking_delta", "thinking": b.get("thinking", "")},
                },
                {
                    "type": "content_block_delta",
                    "index": i,
                    "delta": {"type": "signature_delta", "signature": b.get("signature", "")},
                },
            ]
        elif t in ("tool_use", "server_tool_use"):
            out += [
                {"type": "content_block_start", "index": i, "content_block": {**b, "input": {}}},
                {
                    "type": "content_block_delta",
                    "index": i,
                    "delta": {
                        "type": "input_json_delta",
                        "partial_json": json.dumps(b.get("input") or {}, ensure_ascii=False),
                    },
                },
            ]
        else:  # web_search_tool_result and any other complete block
            out.append({"type": "content_block_start", "index": i, "content_block": b})
        out.append({"type": "content_block_stop", "index": i})
    out.append(
        {
            "type": "message_delta",
            "delta": {"stop_reason": msg.get("stop_reason"), "stop_sequence": msg.get("stop_sequence")},
            "usage": usage,
        }
    )
    out.append({"type": "message_stop"})
    return out


class OpenAIStreamTranslator:
    """OpenAI chat chunks in, Anthropic stream events out.

    ``message_start`` is sent with ``start_usage`` (the calibrated estimate, because OpenAI reports usage last);
    the final ``message_delta`` carries the real usage. Blocks are opened and closed as the kind of delta changes;
    a thinking block is closed with a ``signature_delta`` carrying the bridge-generated signature.
    """

    def __init__(
        self, *, model: str | None, start_usage: dict[str, Any] | None = None, message_id: str | None = None
    ) -> None:
        self.model = model
        self.message_id = message_id or new_message_id()
        self.start_usage = dict(start_usage or {"input_tokens": 0, "output_tokens": 1})
        self.started = False
        self.finished = False
        self.index = -1
        self._open: str | None = None  # thinking | text | tool_use
        self._open_tool: int | None = None  # OpenAI tool index of the open tool_use block
        self._thinking: list[str] = []
        self._stop: str | None = None
        self.usage: dict[str, Any] | None = None  # OpenAI-shaped usage, as seen
        self.stop_reason: str = "end_turn"

    def _start(self, chunk: dict[str, Any] | None) -> list[dict[str, Any]]:
        if self.started:
            return []
        self.started = True
        if chunk and chunk.get("model") and not self.model:
            self.model = chunk["model"]
        return [
            {
                "type": "message_start",
                "message": {
                    "id": self.message_id,
                    "type": "message",
                    "role": "assistant",
                    "model": self.model,
                    "content": [],
                    "stop_reason": None,
                    "stop_sequence": None,
                    "usage": {"output_tokens": 1, **self.start_usage},
                },
            },
            {"type": "ping"},
        ]

    def _close(self) -> list[dict[str, Any]]:
        if self._open is None:
            return []
        out: list[dict[str, Any]] = []
        if self._open == "thinking":
            sig = sign("".join(self._thinking))
            out.append(
                {
                    "type": "content_block_delta",
                    "index": self.index,
                    "delta": {"type": "signature_delta", "signature": sig},
                }
            )
            self._thinking = []
        out.append({"type": "content_block_stop", "index": self.index})
        self._open = self._open_tool = None
        return out

    def _open_block(self, kind: str, block: dict[str, Any]) -> list[dict[str, Any]]:
        out = self._close()
        self.index += 1
        self._open = kind
        out.append({"type": "content_block_start", "index": self.index, "content_block": block})
        return out

    def feed(self, chunk: dict[str, Any] | str) -> list[dict[str, Any]]:
        if self.finished:
            return []
        if isinstance(chunk, str):  # "[DONE]"
            return self.finish()
        out = self._start(chunk)
        if isinstance(chunk.get("usage"), dict):
            self.usage = chunk["usage"]
        choices = chunk.get("choices") or []
        if not choices:
            return out
        ch = choices[0]
        delta = ch.get("delta") or {}
        reasoning = delta.get("reasoning_content") or delta.get("reasoning")
        if isinstance(reasoning, str) and reasoning:
            if self._open != "thinking":
                out += self._open_block("thinking", {"type": "thinking", "thinking": "", "signature": ""})
            self._thinking.append(reasoning)
            out.append(
                {
                    "type": "content_block_delta",
                    "index": self.index,
                    "delta": {"type": "thinking_delta", "thinking": reasoning},
                }
            )
        if delta.get("content"):
            if self._open != "text":
                out += self._open_block("text", {"type": "text", "text": ""})
            out.append(
                {
                    "type": "content_block_delta",
                    "index": self.index,
                    "delta": {"type": "text_delta", "text": delta["content"]},
                }
            )
        for tc in delta.get("tool_calls") or []:
            fn = tc.get("function") or {}
            idx = tc.get("index", 0)
            if tc.get("id") or fn.get("name") or self._open != "tool_use" or self._open_tool != idx:
                out += self._open_block(
                    "tool_use",
                    {
                        "type": "tool_use",
                        "id": tc.get("id") or "toolu_" + uuid.uuid4().hex[:20],
                        "name": fn.get("name", ""),
                        "input": {},
                    },
                )
                self._open_tool = idx
            if fn.get("arguments"):
                out.append(
                    {
                        "type": "content_block_delta",
                        "index": self.index,
                        "delta": {"type": "input_json_delta", "partial_json": fn["arguments"]},
                    }
                )
        if ch.get("finish_reason"):
            self._stop = ch["finish_reason"]
            self.stop_reason = STOP_REASONS.get(self._stop, "end_turn")
            out += self._close()
        return out

    def finish(self) -> list[dict[str, Any]]:
        """The stream is over (``[DONE]`` or the connection closed): final ``message_delta`` and ``message_stop``."""
        if self.finished:
            return []
        self.finished = True
        out = self._start(None) + self._close()
        out.append(
            {
                "type": "message_delta",
                "delta": {"stop_reason": self.stop_reason, "stop_sequence": None},
                "usage": anthropic_usage(self.usage) if self.usage else {"output_tokens": 0},
            }
        )
        out.append({"type": "message_stop"})
        return out
