"""Run the vendored Observatory token check (``check_tokens.py``) and generate token contracts.

``check_tokens.py`` resolves ``var()`` names per file, so the builder writes a token contract comment
(``--name: tokens;`` lines between ``@contract-start`` and ``@contract-end``) into the inline style block of
``index.html``, generated from the ``var()`` calls the page actually makes and checked against tokens.css,
exactly as the design system's own ``build.py`` does for components.css.
"""

from __future__ import annotations

import importlib.util
import re
from pathlib import Path
from types import ModuleType

VENDOR = Path(__file__).resolve().parent / "vendor" / "observatory"
CONTRACT_START, CONTRACT_END = "@contract-start", "@contract-end"


def _checker() -> ModuleType:
    spec = importlib.util.spec_from_file_location("glmkit_vendor_check_tokens", VENDOR / "check_tokens.py")
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def check_files(files: list[Path]) -> list[str]:
    """Findings as 'file:line rule what' strings (empty = clean)."""
    mod = _checker()
    out = []
    for f in files:
        for n, rule, what in mod.check(str(f)):
            out.append(f"{f}:{n} {rule} {what}")
    return out


def defined_tokens() -> set[str]:
    return set(re.findall(r"(--[\w-]+)\s*:", (VENDOR / "tokens.css").read_text(encoding="utf-8")))


def contract_block(text: str) -> tuple[str, list[str]]:
    """Contract comment for every ``var(--x)`` in ``text`` that tokens.css defines, plus the names it does not."""
    used = sorted(set(re.findall(r"var\((--[\w-]+)", text)))
    local = set(re.findall(r"(--[\w-]+)\s*:", text))
    known = defined_tokens()
    external = [u for u in used if u not in local and not u.startswith("--k")]
    missing = [u for u in external if u not in known]
    body = "\n".join(f" *   {name}: tokens;" for name in external if name in known)
    head = "/* Token contract (generated by glmkit report build; see tokencheck.py)"
    return f"{head}\n * {CONTRACT_START}\n{body}\n * {CONTRACT_END}\n */", missing
