/* Cost tab: token treemap, per-turn cache-hit bars with break markers, causes, verbosity, projection.
   Estimates (causes, prompt composition, what-ifs, plan credits) sit in dashed `heuristic` cards or pills. */
GLMKit.registerPage("cost", {
  render(panel, data, kit) {
    const { O, el } = kit;
    const usd = (v) => (v == null ? "not logged" : "$" + (Math.abs(v) < 1 ? v.toFixed(4) : v.toFixed(2)));
    const usdNode = (v) => (v == null ? kit.nl() : el("span", { class: "num" }, usd(v)));
    const tok = (v) => (v == null ? "not logged" : O.fmtK(v));
    const heur = (tip) => O.pill("heuristic", "heur", tip ? { "data-tip": tip } : {});
    const card = (cls, title, hint, ...body) => el("div", { class: "card " + cls },
      el("div", { class: "card-h" }, el("h2", {}, title), el("span", { class: "hint" }, hint)), ...body);
    const wrap = (node) => el("div", { class: "tbl-wrap free" }, node);
    const T = data.totals;
    const BUCKET_COLOR = { "cached input": "--cat-3", "fresh input": "--cat-1", "reasoning output": "--cat-2", "answer output": "--cat-4" };
    const syn = T.synthetic ? el("div", { class: "card heuristic" }, el("div", { class: "card-b" }, O.pill("synthetic", "heur"),
      " These traces are synthetic, generated by `glmkit cost demo` with planted cache breaks. They show what the tab does, not what GLM costs.")) : null;

    /* where tokens went: exact usage buckets, per model */
    const tmap = el("div", { class: "tmap", role: "list", "aria-label": "Token treemap" });
    const tm = card("c-7", "Where tokens went", "area = tokens · colour = bucket · exact usage numbers", el("div", { class: "card-b" }, tmap));
    const comp = el("div", { class: "card-b" });
    const compCard = card("c-5 heuristic", "Prompt composition", "input tokens shared out by character share of each prompt part", comp);
    compCard.querySelector(".card-h").append(heur("Characters are only a proxy for tokens"));
    const cmpParts = (data.input_composition || []).map((c, i) => ({ label: c.component, value: c.tokens, color: "--cat-" + ((i % 8) + 1) }));
    comp.replaceChildren(cmpParts.length ? O.compositionBar(cmpParts, { format: tok, label: "Input prompt composition" }) : O.emptyState("No input usage logged."));

    /* per-turn cache hit bars */
    const sel = { trace: (data.traces.find((t) => t.breaks) || data.traces[0] || {}).trace_id };
    const turnsHost = el("div", { class: "turns", role: "group", "aria-label": "Cache hit per turn" });
    const detail = el("div", { class: "cause-detail" });
    const traceList = el("div");
    const turnsCard = card("c-12", "Cache hit by turn", "bar height = share of the prompt served from cache · ✕ = cache broke · click a bar",
      el("div", { class: "card-b" }, el("div", { class: "grid" }, el("div", { class: "c-4" }, traceList), el("div", { class: "c-8" }, turnsHost, el("div", { class: "cost-axis" }, el("span", {}, "call 0"), el("span", {}, "later calls →")), detail))));
    function drawTraces() {
      traceList.replaceChildren(O.barList(data.traces.map((t) => ({
        label: t.trace_id, mono: true, value: t.cache_share == null ? 0 : t.cache_share, meta: `${t.calls} calls`,
        tone: t.breaks ? "err" : "ok", pill: t.breaks ? O.pill(`${t.breaks} break${t.breaks > 1 ? "s" : ""}`, "err") : null,
        tip: `${t.trace_id}\ncache hit ${O.fmtPct(t.cache_share)}${t.first_break_cause ? "\nfirst break at call " + t.first_break_seq + ": " + t.first_break_cause : ""}`,
        onClick: () => { sel.trace = t.trace_id; drawTurns(); },
      })), { format: (v) => O.fmtPct(v, 0), max: 1, empty: "No traces." }));
    }
    let selTurn = null;
    function drawTurns() {
      const turns = (data.turns || {})[sel.trace] || [];
      const firstBreak = turns.find((t) => t.broke);
      turnsHost.replaceChildren(...turns.map((t) => {
        const share = t.cache_share;
        const cls = "turn" + (t.broke ? " is-break" : "") + (share == null ? " is-nolog" : "") + (firstBreak && firstBreak.seq === t.seq ? " first" : "");
        const tip = `call ${t.seq}\ncache hit ${O.fmtPct(share)}\nreuse of prior prompt ${O.fmtPct(t.reuse)}` + (t.broke ? `\nBROKE · likely cause (heuristic): ${t.primary_cause}` : "");
        return el("button", { type: "button", class: cls, "aria-pressed": String(selTurn === t.seq), "aria-label": `Call ${t.seq}: cache hit ${O.fmtPct(share)}${t.broke ? ", cache broke" : ""}`, "data-tip": tip,
          onclick: () => { selTurn = t.seq; drawTurns(); } },
          el("span", { class: "tmark" }, t.broke ? "✕" : ""),
          el("span", { class: "tbar" }, share == null ? null : el("span", { class: "tfill grow-y", style: `height:${Math.max(2, share * 100)}%` })),
          el("span", { class: "tlab" }, String(t.seq)));
      }));
      const t = turns.find((x) => x.seq === selTurn) || firstBreak || turns[1] || turns[0];
      if (!t) { detail.replaceChildren(O.emptyState("No turns.")); return; }
      const rows = [["call", String(t.seq)], ["input tokens", tok(t.input_total)], ["cache read", tok(t.cache_read)],
        ["cache hit", O.fmtPct(t.cache_share)], ["reuse of prior prompt", t.seq === 0 ? "first call" : O.fmtPct(t.reuse)]];
      const out = [O.kvList(rows)];
      if (t.broke) {
        out.push(el("div", {}, O.pill("cache broke", "err"), " ", heur("Cause inferred by diffing this call's prompt against the previous call"), " ",
          el("strong", {}, t.primary_cause === "unattributed" ? "no cause found in the prompt diff (provider-side eviction?)" : t.primary_cause), t.lost_tokens != null ? ` · ${tok(t.lost_tokens)} tokens re-billed as fresh input` : ""));
        for (const c of t.causes) out.push(el("div", { class: "well" }, el("strong", {}, c.cause + (c.subtype ? " / " + c.subtype : "")), ": ", c.detail));
      }
      detail.replaceChildren(...out);
    }

    /* causes */
    const causes = data.causes || [];
    const causeCard = card("c-5 heuristic", "Why the cache broke", "lost cached tokens by likely cause", el("div", { class: "card-b" }, O.barList(causes.map((c, i) => ({
      label: c.label, value: c.lost_tokens, meta: `${c.breaks} break${c.breaks > 1 ? "s" : ""}${c.usd_wasted != null ? " · ~" + usd(c.usd_wasted) : ""}`, color: "--cat-" + ((i % 8) + 1),
      tip: `${c.cause}\n${c.breaks} breaks in ${c.traces.length} trace(s)\n${tok(c.lost_tokens)} tokens re-billed`,
    })), { format: tok, empty: "No cache breaks found." })));
    causeCard.querySelector(".card-h").append(heur("Causes are inferred from prompt diffs, not observed"));

    /* verbosity */
    const vt = el("table");
    const vcard = card("c-7", "Verbosity by effort", "output and reasoning tokens per task (one task = one trace)", wrap(vt));
    const effTone = (e) => (e === "max" ? "warn" : null);
    O.sortableTable(vt, [
      { key: "model", label: "Model", render: (r) => el("span", { class: "mono" }, r.model) },
      { key: "effort", label: "Effort", render: (r) => (r.effort ? O.pill(r.effort, effTone(r.effort)) : kit.nl()) },
      { key: "tasks", label: "Tasks", align: "r", render: (r) => el("span", { class: "num" }, String(r.tasks)) },
      { key: "output_per_task", label: "Output / task", align: "r", render: (r) => el("span", { class: "num" }, tok(r.output_per_task)) },
      { key: "reasoning_per_task", label: "Reasoning / task", align: "r", render: (r) => el("span", { class: "num" }, tok(r.reasoning_per_task)) },
      { key: "reasoning_share", label: "Reasoning share", align: "r", render: (r) => el("span", { class: "num" }, O.fmtPct(r.reasoning_share, 0)) },
    ], data.verbosity.rows, { label: "Verbosity", rowKey: (r) => r.model + r.effort, empty: "No usage logged." });
    const sv = data.verbosity.savings || [];
    if (sv.length) {
      vcard.append(el("div", { class: "card-b" }, el("h3", {}, "Projected saving from a lower effort"), O.barList(sv.map((s) => ({
        label: `${s.model}: ${s.from_effort} → ${s.to_effort}`, mono: true, value: s.tokens_saved_per_task,
        meta: `${O.fmtPct(1 - s.factor, 0)} fewer output tokens/task`,
        pill: s.basis === "measured" ? O.pill("measured", "ok") : heur(s.source || ""),
        tip: `${s.basis} ratio ${s.factor.toFixed(2)}\n${tok(s.output_per_task_now)} → ${tok(s.output_per_task_after)} per task`,
      })), { format: (v) => tok(v) + "/task", empty: "none" })));
    }

    /* tokenizer */
    const tk = data.tokenizer || { by_type: [] };
    const tt = el("table");
    const tkCard = card("c-5", "Tokenizer inflation", "GLM-counted ÷ incumbent-counted input tokens", wrap(tt));
    O.sortableTable(tt, [
      { key: "content_type", label: "Content", render: (r) => O.pill(r.content_type) },
      { key: "samples", label: "Samples", align: "r", render: (r) => el("span", { class: "num" }, String(r.samples)) },
      { key: "ratio", label: "GLM ÷ incumbent", align: "r", render: (r) => (r.ratio == null ? kit.nl() : el("span", { class: "num", "data-tip": `${r.glm_tokens} GLM tokens vs ${r.incumbent_tokens}` }, r.ratio.toFixed(2) + "×")) },
    ], tk.by_type, { label: "Tokenizer inflation", rowKey: (r) => r.content_type });
    if (tk.samples === 0) tkCard.append(el("div", { class: "card-b" }, kit.nl("not logged"), " Pass `--counts counts.jsonl` with both token counts per sample."));

    /* projection */
    const P = data.projection;
    const pt = el("table");
    const pcard = card("c-12", "Same workload, other hosts", `${P.workload.tasks} tasks · ${P.workload.calls} calls · cached input priced separately · prices retrieved ${data.projection.payg.find((r) => r.retrieved)?.retrieved || "not logged"}`, wrap(pt));
    O.sortableTable(pt, [
      { key: "host", label: "Host", render: (r) => el("span", { class: "mono" }, r.host) },
      { key: "model", label: "Model", render: (r) => el("span", { class: "mono" }, r.model) },
      { key: "usd", label: "Workload cost", align: "r", render: (r) => (r.usd != null ? usdNode(r.usd) : r.usd_upper_bound != null
        ? el("span", {}, kit.nl(), " ", O.pill("≤ " + usd(r.usd_upper_bound), "heur", { "data-tip": "Upper bound: cached tokens priced as fresh input (cached price not logged)" })) : kit.nl()),
        value: (r) => r.usd ?? r.usd_upper_bound ?? -1 },
      { key: "usd_per_task", label: "Per task", align: "r", render: (r) => usdNode(r.usd_per_task) },
      { key: "usd_if_cache_fixed", label: "If cache breaks fixed", align: "r", render: (r) => (r.usd_if_cache_fixed == null ? kit.nl() : el("span", {}, usdNode(r.usd_if_cache_fixed), " ", heur("Lost prefix tokens re-priced as cached input"))) },
      { key: "prices", label: "In / cached / out per 1M", render: (r) => (r.prices ? el("span", { class: "num t-meta" }, ["input", "cached_input", "output"].map((k) => (r.prices[k] == null ? "not logged" : r.prices[k])).join(" / ")) : kit.nl()) },
      { key: "src", label: "Source", render: (r) => (r.source ? el("a", { href: r.source, target: "_blank", rel: "noreferrer noopener", class: "t-meta" }, "price source") : kit.nl()) },
    ], P.payg, { label: "Projection", rowKey: (r) => r.host + r.model, sort: { key: "usd", dir: 1 }, empty: "No priced hosts." });

    const CP = P.coding_plan;
    const ct = el("table");
    const cpcard = card("c-12 heuristic", "Coding Plan", `published: tier price, 5-hour and weekly credit caps · peak ${CP.peak_window} · off-peak ×${CP.off_peak_multiplier} · credits per token NOT published`, wrap(ct));
    cpcard.querySelector(".card-h").append(heur("Plan fit needs a credits-per-USD conversion Z.ai does not publish"));
    const win = (o) => (o ? `${O.fmtN(o.peak)} peak · ${O.fmtN(o.off_peak)} off-peak · ${O.fmtN(o.peak_reported)} at ×${CP.reported_peak_multiplier}` : null);
    O.sortableTable(ct, [
      { key: "tier", label: "Tier", render: (r) => O.pill(r.tier) },
      { key: "usd_per_month", label: "Per month", align: "r", render: (r) => el("span", { class: "num", "data-tip": `quarterly ${usd(r.usd_per_month_quarterly)}/mo · yearly ${usd(r.usd_per_month_yearly)}/mo` }, "$" + r.usd_per_month) },
      { key: "credits_5h", label: "5-hour cap", align: "r", render: (r) => el("span", { class: "num" }, O.fmtN(r.credits_5h)) },
      { key: "credits_weekly", label: "Weekly cap", align: "r", render: (r) => el("span", { class: "num" }, O.fmtN(r.credits_weekly)) },
      { key: "break_even_tasks_per_month", label: `Break-even tasks / month vs ${P.reference.host}`, align: "r", render: (r) => (r.break_even_tasks_per_month == null ? kit.nl() : el("span", { class: "num" }, O.fmtN(r.break_even_tasks_per_month))) },
      { key: "tasks_per_5h", label: "Tasks per 5 hours", align: "r", render: (r) => (r.tasks_per_5h ? el("span", { class: "num t-meta" }, win(r.tasks_per_5h)) : kit.nl()) },
      { key: "tasks_per_week", label: "Tasks per week", align: "r", render: (r) => (r.tasks_per_week ? el("span", { class: "num t-meta" }, win(r.tasks_per_week)) : kit.nl()) },
    ], CP.tiers, { label: "Coding Plan tiers", rowKey: (r) => r.tier });
    if (CP.credits_per_usd == null) cpcard.append(el("div", { class: "card-b" }, kit.nl(), " Tasks per window need `--credits-per-usd` (your own heuristic conversion)."));

    const assume = card("c-12 heuristic", "Assumptions", "read before quoting a number",
      el("div", { class: "card-b" }, el("ul", { class: "assume" }, ...P.assumptions.map((a) => el("li", {}, a)))));

    panel.replaceChildren(el("div", { class: "grid" }, ...(syn ? [el("div", { class: "c-12" }, syn)] : []), tm, compCard, turnsCard, causeCard, vcard, tkCard, pcard, cpcard, assume));

    O.treemap(tmap, data.token_buckets.map((b) => ({ id: b.model + b.bucket, label: `${b.model} · ${b.bucket}`, value: b.tokens, color: BUCKET_COLOR[b.bucket] || "--kind-other" })),
      { format: tok, label: "Tokens by bucket", max: 12 });
    drawTraces();
    drawTurns();
  },
  onShow(data, kit) {
    // USD tiles need a format function, which JSON cannot carry
    const usd = (v) => (v == null ? "not logged" : "$" + (v < 1 ? v.toFixed(4) : v.toFixed(2)));
    kit.setKpis(data.kpis.map((t) => (t.format === "usd" ? { ...t, format: usd } : t)));
  },
});
